/*
 * Paint → code mapping (Phase 1). Color fields may hold theme tokens
 * ({ token: 'primary' }) or gradients; generated code represents them as:
 *
 *   token    → `colors.primary` (RawCode identifier) against the screen's
 *              `const { colors } = useTheme()` — the plain-TS theme pattern
 *              from the reference apps (constants/theme.ts + hooks/useTheme.ts,
 *              no NativeWind). The screen emitter adds the hook line + import
 *              when any token was used (tracked in PaintUsage).
 *   gradient → (backgroundColor only) the element becomes an
 *              expo-linear-gradient <LinearGradient colors locations start end>
 *              wrapper carrying the node's remaining style; children render
 *              inside (exactly what the dedicated lineargradient entry emits).
 *              Radial is emitted as linear — expo-linear-gradient has no radial
 *              mode; the picker states this while editing.
 *   gradient on a non-background key (not offered by the UI, but the model
 *   allows it) → degrades to the first stop's solid color.
 */

import { RawCode, jsStringLiteral } from './format'
import { COLOR_STYLE_KEYS, isGradientPaint, isTokenPaint, normalizeStops } from '@/lib/paint'

/** Tracks what a file's emitted tree used, so imports/hook lines stay exact. */
export interface PaintUsage {
  /** Theme token names referenced (drives useTheme import + hook line). */
  tokens: Set<string>
}

export function newPaintUsage(): PaintUsage {
  return { tokens: new Set() }
}

/** Identifier-safe token name ('my token' can't exist — store validates). */
export function tokenIdent(name: string): string {
  return name.replace(/[^a-zA-Z0-9_$]/g, '')
}

/** `colors.primary` expression for a token paint. */
export function tokenCode(name: string): RawCode {
  return new RawCode(`colors.${tokenIdent(name)}`)
}

/**
 * Map a node style record's color keys for code emission. Gradient
 * backgroundColor is handled SEPARATELY by the element swap (the caller checks
 * hasGradientFill first and must NOT see it here); other gradients degrade to
 * their first stop color.
 */
export function paintsForCodegen(style: Record<string, unknown>, usage: PaintUsage): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  let changed = false
  for (const key of Object.keys(style)) {
    const value = style[key]
    if (!COLOR_STYLE_KEYS.includes(key) || value === undefined || value === null) {
      out[key] = value
      continue
    }
    if (isTokenPaint(value)) {
      usage.tokens.add(value.token)
      out[key] = tokenCode(value.token)
      changed = true
      continue
    }
    if (isGradientPaint(value)) {
      out[key] = normalizeStops(value.stops)[0].color
      changed = true
      continue
    }
    out[key] = value
  }
  return changed ? out : style
}

/** True when the style carries a gradient fill on backgroundColor. */
export function hasGradientFill(style: Record<string, unknown>): boolean {
  return isGradientPaint(style.backgroundColor)
}

/**
 * Gradient fill → <LinearGradient> attributes (colors, locations when
 * non-uniform, start/end from the builder angle — the exact math of the
 * lineargradient entry emitter, angle convention locked with the preview).
 */
export function gradientAttrs(gradient: {
  type: string
  angle?: number
  stops: { color: string; position: number }[]
}): { colors: string[]; locations?: number[]; start: { x: number; y: number }; end: { x: number; y: number } } {
  const stops = normalizeStops(gradient.stops)
  const colors = stops.map((s) => s.color)
  const locations = stops.map((s) => Math.round(s.position * 100) / 100)
  const uniform = locations.every((p, i) => p === (i / (locations.length - 1)))
  // 0° is a VALID angle — guard with isFinite, never `|| default` (falsy-zero bug).
  const rawAngle = gradient.type === 'radial-gradient' ? 180 : Number(gradient.angle)
  const angle = Number.isFinite(rawAngle) ? rawAngle : 45
  const rad = (angle * Math.PI) / 180
  const round2 = (n: number): number => Math.round(n * 100) / 100
  return {
    colors,
    ...(uniform ? {} : { locations }),
    start: { x: round2(0.5 - 0.5 * Math.cos(rad)), y: round2(0.5 - 0.5 * Math.sin(rad)) },
    end: { x: round2(0.5 + 0.5 * Math.cos(rad)), y: round2(0.5 + 0.5 * Math.sin(rad)) }
  }
}

/* ── generated theme files (plain TS, the TravelMate / Expo template way) ── */

/** `constants/theme.ts` — light/dark color maps. */
export function renderThemeConstants(colors: Record<string, { light: string; dark: string }>): string {
  const names = Object.keys(colors).sort()
  const body = (mode: 'light' | 'dark') =>
    names.map((n) => `  ${tokenIdent(n)}: ${jsStringLiteral(colors[n][mode])},`).join('\n')
  return [
    '/*',
    ' * Project theme — generated by ExpoForge.',
    ' * Plain TypeScript light/dark palettes (no NativeWind/uniwind): consumed',
    ' * through useTheme() in @/hooks/useTheme, mirroring the Expo default',
    ' * template and the reference apps (constants/theme pattern).',
    ' */',
    '',
    'export const COLORS = {',
    '  light: {',
    body('light'),
    '  },',
    '  dark: {',
    body('dark'),
    '  },',
    '} as const;',
    '',
    'export type ThemeColorName = keyof typeof COLORS.light;',
    ''
  ].join('\n')
}

/** `hooks/useTheme.ts` — the tiny hook screens use when a style holds tokens. */
export function renderUseThemeHook(): string {
  return [
    '/*',
    ' * Generated by ExpoForge — resolves the project palette by color scheme.',
    ' */',
    "import { useColorScheme } from 'react-native';",
    '',
    "import { COLORS } from '@/constants/theme';",
    '',
    'export function useTheme() {',
    "  const scheme = useColorScheme();",
    "  const mode = scheme === 'dark' ? 'dark' : 'light';",
    '  return { mode, colors: COLORS[mode] };',
    '}',
    ''
  ].join('\n')
}
